// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds the
// pre-token protocols below the watchlist floor the radar exists to find. A protocol is pre-token
// when its record carries no token (no market cap, no CoinGecko id, no symbol); the live-token
// protocols are kept apart and shown with the market's own values, never mixed into the ranking.
//
// Implied value follows only from the snapshot's own figures. The category multiple is calibrated
// from the snapshot itself: for each category, the median market-cap-to-TVL ratio of its tokenized
// protocols (market cap above zero, so a token with no price carries no signal). A category with
// fewer than three such peers falls back to its nearest neighbour category's median, or to the
// global median when it has none; the final multiple is clamped to [0.05, 1.0]. Then:
//
//   implied = TVL x category_multiple x growth_mult x maturity_mult
//   growth_mult   = 1 + clamp(change_7d, -60, 120) / 100 x 0.5
//   maturity_mult = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age unknown: 365 days)
//
// No protocol name is ever special-cased: the same function scores every row, and the dashboard
// states the calibration table so the judge can check every number against the snapshot.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

